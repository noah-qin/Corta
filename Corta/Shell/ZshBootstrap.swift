import Foundation

/// Per-session startup wrappers source the user's files, then the bundled hooks.
/// No edits to ~/.zshrc. ZDOTDIR is restored before the user's .zshrc runs.
enum ZshBootstrap {
    private static var folders: [URL] = []
    static func removeGeneratedFiles() {
        for folder in folders { try? FileManager.default.removeItem(at: folder) }
        folders.removeAll()
    }

    /// One session's folder, once its shell no longer needs it: a spawn
    /// that failed, or a session that ended. Every tab, fallback rung and
    /// reconnect makes one, and a long-running app kept them all until quit.
    static func remove(_ folder: URL) {
        guard let index = folders.firstIndex(of: folder) else { return }
        folders.remove(at: index)
        try? FileManager.default.removeItem(at: folder)
    }

    /// Folders a run that never reached `removeGeneratedFiles` — a crash, a
    /// force quit — left behind. Only day-old ones: the development and
    /// release builds share the temporary directory, and the other may be
    /// starting a shell from a fresh folder right now.
    nonisolated static func removeStaleFolders(
        in directory: URL = FileManager.default.temporaryDirectory, now: Date = Date()
    ) {
        let fm = FileManager.default
        guard let names = try? fm.contentsOfDirectory(atPath: directory.path) else { return }
        for name in names where name.hasPrefix(folderPrefix) {
            let url = directory.appendingPathComponent(name)
            guard let modified = (try? fm.attributesOfItem(atPath: url.path))?[.modificationDate] as? Date,
                now.timeIntervalSince(modified) > staleAge
            else { continue }
            try? fm.removeItem(at: url)
        }
    }

    nonisolated static let folderPrefix = "corta-zsh-"
    nonisolated static let staleAge: TimeInterval = 24 * 3600
    static func environment(_ original: [String: String], executable: String, arguments: [String]) -> [String: String] {
        prepare(original, executable: executable, arguments: arguments).environment
    }

    /// The child's environment; the wrapper folder it points zsh at, for
    /// `remove(_:)` once the session no longer needs it; and the token the
    /// directory-completion widget puts before its reports, for the
    /// session's `Terminal`. Both nil when the shell is not a login zsh or
    /// the folder could not be written.
    static func prepare(
        _ original: [String: String], executable: String, arguments: [String]
    ) -> (environment: [String: String], folder: URL?, token: String?) {
        guard (executable as NSString).lastPathComponent == "zsh",
            arguments == ["-l"] || arguments.isEmpty else { return (original, nil, nil) }
        let fm = FileManager.default
        let folder = fm.temporaryDirectory.appendingPathComponent(folderPrefix + UUID().uuidString)
        let userDirectory = original["ZDOTDIR"] ?? original["HOME"] ?? NSHomeDirectory()
        // Quotes are generated by the application, not by a terminal report.
        func quote(_ value: String) -> String { "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'" }
        do {
            try fm.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            let hook = folder.appendingPathComponent("corta.zsh")
            try ShellIntegrationScript.script(for: .zsh).write(to: hook, atomically: true, encoding: .utf8)
            let restore = "if [[ $CORTA_USER_ZDOTDIR_SET == 1 ]]; then ZDOTDIR=$CORTA_USER_ZDOTDIR; else unset ZDOTDIR; fi\n"
            let capture = "export CORTA_USER_ZDOTDIR=${ZDOTDIR:-$HOME}\nexport CORTA_USER_ZDOTDIR_SET=${+ZDOTDIR}\n"
            for file in [".zshenv", ".zprofile"] {
                let script = restore + "[[ -r ${ZDOTDIR:-$HOME}/\(file) ]] && source ${ZDOTDIR:-$HOME}/\(file)\n" + capture + "ZDOTDIR=\(quote(folder.path))\n"
                try script.write(to: folder.appendingPathComponent(file), atomically: true, encoding: .utf8)
            }
            // macOS's /etc/zshrc runs between the wrappers, while ZDOTDIR
            // still names this folder, and sets HISTFILE from it: history
            // went here and was deleted with the folder. Pointed back at the
            // user's directory unless their own files chose another.
            let history = "[[ $HISTFILE == \(quote(folder.appendingPathComponent(".zsh_history").path)) ]] && HISTFILE=${ZDOTDIR:-$HOME}/.zsh_history\n"
            // A shell variable, never exported: no command the shell runs,
            // and nothing a remote host prints, can learn it.
            let token = UUID().uuidString
            let secret = "typeset -g __corta_cd_token=\(token)\n"
            let rc = restore + history + secret + "unset CORTA_USER_ZDOTDIR CORTA_USER_ZDOTDIR_SET\n[[ -r ${ZDOTDIR:-$HOME}/.zshrc ]] && source ${ZDOTDIR:-$HOME}/.zshrc\nsource \(quote(hook.path))\n"
            try rc.write(to: folder.appendingPathComponent(".zshrc"), atomically: true, encoding: .utf8)
            folders.append(folder)
            var env = original
            env["CORTA_USER_ZDOTDIR"] = userDirectory
            env["CORTA_USER_ZDOTDIR_SET"] = original["ZDOTDIR"] == nil ? "0" : "1"
            env["ZDOTDIR"] = folder.path
            return (env, folder, token)
        } catch {
            try? fm.removeItem(at: folder)
            return (original, nil, nil)
        }
    }
}
