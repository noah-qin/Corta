export function dictionary(lang: string): Dictionary {
  const row = rows[lang] || rows.en;
  if (row.length !== keys.length)
    throw Error(`Incomplete UI dictionary: ${lang}`);
  return Object.fromEntries(keys.map((key, i) => [key, row[i]])) as Dictionary;
}
export function label(lang: string, slug: string) {
  const d = dictionary(lang);
  return slug === "features" ? d.features : d[slug as keyof Dictionary] || slug;
}

