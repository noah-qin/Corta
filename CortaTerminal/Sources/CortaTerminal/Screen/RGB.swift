/// An 8-bit sRGB triple: a direct colour's components, a palette entry, or
/// a dynamic colour as a program sets and queries it.
public struct RGB: Hashable, Sendable {
    public var red: UInt8
    public var green: UInt8
    public var blue: UInt8

    public init(red: UInt8, green: UInt8, blue: UInt8) {
        self.red = red
        self.green = green
        self.blue = blue
    }
}
