func supportsEmojiPresentation(_ scalar: UInt32) -> Bool {
    var low = 0
    var high = emojiPresentationBases.count
    while low < high {
        let mid = (low + high) / 2
        let range = emojiPresentationBases[mid]
        if scalar < range.0 { high = mid }
        else if scalar > range.1 { low = mid + 1 }
        else { return true }
    }
    return false
}
